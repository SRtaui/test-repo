class СоциальнаяСеть:
    """
    Базовый класс для представления социальной сети.
    
    Атрибуты:
        название (str): Название социальной сети.
        год_основания (int): Год основания социальной сети.
        активные_пользователи (int): Количество активных пользователей.
    """
    
    def __init__(self, название: str, год_основания: int, активные_пользователи: int):
        """
        Конструктор базового класса.
        
        Аргументы:
            название (str): Название социальной сети.
            год_основания (int): Год основания социальной сети.
            активные_пользователи (int): Количество активных пользователей.
        """
        self.название = название
        self.год_основания = год_основания
        self.активные_пользователи = активные_пользователи
    
    def __str__(self) -> str:
        """
        Возвращает строковое представление объекта.
        
        Возвращает:
            str: Строковое представление социальной сети.
        """
        return f"{self.название} (основана в {self.год_основания}), активные пользователи: {self.активные_пользователи}"
    
    def __repr__(self) -> str:
        """
        Возвращает формальное строковое представление объекта.
        
        Возвращает:
            str: Формальное строковое представление социальной сети.
        """
        return f"СоциальнаяСеть(название={self.название!r}, год_основания={self.год_основания!r}, активные_пользователи={self.активные_пользователи!r})"
    
    def количество_лет_с_основания(self, текущий_год: int) -> int:
        """
        Возвращает количество лет с момента основания социальной сети.
        
        Аргументы:
            текущий_год (int): Текущий год.
        
        Возвращает:
            int: Количество лет с момента основания.
        """
        return текущий_год - self.год_основания
class VK(СоциальнаяСеть):
    """
    Дочерний класс для представления социальной сети VK.
    
    Атрибуты:
        название (str): Название социальной сети.
        год_основания (int): Год основания социальной сети.
        активные_пользователи (int): Количество активных пользователей.
        страна (str): Страна, в которой основана социальная сеть.
    """
    
    def __init__(self, название: str, год_основания: int, активные_пользователи: int, страна: str):
        """
        Конструктор дочернего класса.
        
        Аргументы:
            название (str): Название социальной сети.
            год_основания (int): Год основания социальной сети.
            активные_пользователи (int): Количество активных пользователей.
            страна (str): Страна, в которой основана социальная сеть.
        """
        super().__init__(название, год_основания, активные_пользователи)
        self.страна = страна
    
    def __str__(self) -> str:
        """
        Возвращает строковое представление объекта.
        
        Возвращает:
            str: Строковое представление социальной сети VK.
        """
        return f"{super().__str__()}, страна: {self.страна}"
    
    def __repr__(self) -> str:
        """
        Возвращает формальное строковое представление объекта.
        
        Возвращает:
            str: Формальное строковое представление социальной сети VK.
        """
        return f"VK(название={self.название!r}, год_основания={self.год_основания!r}, активные_пользователи={self.активные_пользователи!r}, страна={self.страна!r})"
    
    def количество_лет_с_основания(self, текущий_год: int) -> int:
        """
        Перегрузка метода для учета особенностей VK.
        
        Причина перегрузки: VK была основана в России, и в некоторых случаях
        требуется учитывать дополнительные факторы, такие как локальные праздники
        или события, которые могут повлиять на расчет.
        
        Аргументы:
            текущий_год (int): Текущий год.
        
        Возвращает:
            int: Количество лет с момента основания.
        """
        return super().количество_лет_с_основания(текущий_год)
    
    def информация_о_стране(self) -> str:
        """
        Возвращает информацию о стране, в которой основана социальная сеть.
        
        Возвращает:
            str: Информация о стране.
        """
        return f"Социальная сеть {self.название} основана в {self.страна}."
